use rustkvm::network::{parse_default_gateway, parse_nameservers};

// Captured from the dev board with both NICs on DHCP (eth0 via udhcpc,
// eth1 via dhcpcd with metric 1003).
const ROUTES: &str = "\
Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT
eth1\t00000000\t0101A8C0\t0003\t0\t0\t1003\t00000000\t0\t0\t0
eth0\t00000000\t0101A8C0\t0003\t0\t0\t0\t00000000\t0\t0\t0
eth0\t0001A8C0\t00000000\t0001\t0\t0\t0\t00FFFFFF\t0\t0\t0
eth1\t0001A8C0\t00000000\t0001\t0\t0\t1003\t00FFFFFF\t0\t0\t0
";

#[test]
fn default_gateway_picks_lowest_metric_route() {
    assert_eq!(parse_default_gateway(ROUTES).as_deref(), Some("192.168.1.1"));
}

#[test]
fn default_gateway_prefers_lower_metric_interface() {
    let routes = "\
Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT
eth0\t00000000\t0101A8C0\t0003\t0\t0\t1002\t00000000\t0\t0\t0
eth1\t00000000\t0A01A8C0\t0003\t0\t0\t10\t00000000\t0\t0\t0
";
    assert_eq!(parse_default_gateway(routes).as_deref(), Some("192.168.1.10"));
}

#[test]
fn default_gateway_absent_without_default_route() {
    let routes = "\
Iface\tDestination\tGateway \tFlags\tRefCnt\tUse\tMetric\tMask\t\tMTU\tWindow\tIRTT
eth0\t0001A8C0\t00000000\t0001\t0\t0\t0\t00FFFFFF\t0\t0\t0
";
    assert_eq!(parse_default_gateway(routes), None);
    assert_eq!(parse_default_gateway(""), None);
}

#[test]
fn nameservers_are_deduplicated_and_comments_ignored() {
    let resolv = "\
# Generated by dhcpcd from eth1.dhcp
nameserver 192.168.1.1
search lan
nameserver 192.168.1.1 # eth1
nameserver fe80::1
nameserver not-an-ip
";
    assert_eq!(parse_nameservers(resolv), vec!["192.168.1.1", "fe80::1"]);
}
